test('截图原句经过语义理解，只答能力，不查询或改写行程',async({page})=>{
 await page.goto('/assistant?context=city')
 const input=page.getByLabel('告诉小汴梁你的问题或想调整的安排',{exact:true})
 await expect(input).toBeEnabled()
 const before=(await(await page.request.get('/api/city/v1/trips/current')).json()).trip
 const path='/api/city/v1/trips/'+before.id
 const workspaceBefore=await(await page.request.get(path+'/services')).json()
 await input.fill('你能查阅相关酒店资料吗')
 const resultResponse=page.waitForResponse(r=>r.url().endsWith('/step')&&r.request().method()==='POST')
 await page.getByRole('button',{name:'发送',exact:true}).click()
 const result=await(await resultResponse).json()
 expect(result.mode).toBe('conversation')
 expect(result.status).toBe('answered')
 expect(result.metrics.model_calls).toBe(1)
 expect(result.metrics.tools).toBe(0)
 await expect(page.locator('.agent-messages')).toContainText('可以查询酒店名称、地址和展示起价')
 await expect(page.locator('.agent-messages')).not.toContainText('请先明确')
 await expect(page.getByLabel('住宿与周边候选')).toHaveCount(0)
 expect(await(await page.request.get(path)).json()).toEqual(before)
 expect(await(await page.request.get(path+'/services')).json()).toEqual(workspaceBefore)
})

