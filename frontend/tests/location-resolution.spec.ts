import {test,expect} from '@playwright/test'
import {fileURLToPath} from 'node:url'
test.use({timezoneId:'UTC'})

test('地点候选须明确确认，确认后仍保留资料缺口与正式路线版本',async({page})=>{
 await page.setViewportSize({width:465,height:769})
 await page.route('**/api/city/v1/facts',r=>r.fulfill({json:{items:[]}}))
 await page.request.post('/api/v1/sessions')
 const trip=await(await page.request.post('/api/city/v1/trips',{data:{request_id:crypto.randomUUID(),draft:{}}})).json()
 const constraints={business_date:'2030-05-01',starts_at:'2030-05-01T09:00:00+08:00',ends_at:'2030-05-01T18:00:00+08:00',origin_place_id:null,destination_place_id:null,origin_text:'开封站',destination_text:'清明上河园',modes:['walking'],pace:'standard',objective:'balanced',budget_fen:null}
 await page.request.post(`/api/city/v1/trips/${trip.id}/exploration/preview`,{data:{request_id:crypto.randomUUID(),expected_version:trip.version,basket_version:0,planning_version:0,constraints}})
 const candidates=['[合成测试]开封站','[合成测试]开封北站'].map((name,i)=>({candidate_id:'test:'+i,poi_id:'test-poi:'+i,name,address:'[合成测试]地址'+i,longitude:114.3,latitude:34.8,category:'车站',entrance_status:'needs_entrance_verification',fact_status:'provider_candidate_only'}))
 let confirms=0,engineWrites=0
 await page.route('**/api/city/v1/locations/search',r=>r.fulfill({json:{status:'candidates',resolution_id:'test-resolution',query:'开封站',provider_status:'found',candidates,requires_user_confirmation:true,expires_in_seconds:900}}))
 await page.route('**/api/city/v1/locations/test-resolution/confirm',r=>{confirms++;const body=r.request().postDataJSON();return r.fulfill({json:{status:'needs_data',selected:candidates.find(c=>c.candidate_id===body.candidate_id),formal_fact_status:'provider_candidate_only'}})})
 page.on('request',r=>{if(r.method()==='POST'&&r.url().endsWith('/engine/confirm'))engineWrites++})
 await page.goto(`/assistant?context=city&city_trip=${trip.id}&plan=basket`)
 await page.getByRole('button',{name:'核对出发与返回地点',exact:true}).click()
 await page.getByRole('button',{name:'查找并核对出发地点',exact:true}).click()
 const picker=page.getByRole('region',{name:'出发地点地点核对',exact:true})
 await expect(picker.getByRole('button',{name:'确认此地点',exact:true})).toHaveCount(2)
 expect(confirms).toBe(0)
 await picker.getByRole('button',{name:'确认此地点',exact:true}).nth(1).click()
 await expect(picker).toContainText('出入口、开放时间与交通依据仍待核验')
 await expect(page.getByLabel('出发地点',{exact:true})).toHaveValue('[合成测试]开封北站')
 await page.screenshot({path:fileURLToPath(new URL('../../docs/screenshots/location-confirmation-isolated-mobile.png',import.meta.url)),fullPage:true})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.locator('.planning-question').getByRole('button',{name:'继续',exact:true}).click()
 await expect(page.getByLabel('规划检测结果')).toContainText('位置资料待核验')
 const saved=await(await page.request.get('/api/city/v1/trips/'+trip.id)).json()
 expect(saved.route_version).toBe(0);expect(saved.draft.origin_place_id).toBeNull()
 expect(confirms).toBe(1);expect(engineWrites).toBe(0)
})

test('历史凌晨时段需游客确认，浏览器UTC时区不会改变北京时间',async({page})=>{
 await page.request.post('/api/v1/sessions')
 const trip=await(await page.request.post('/api/city/v1/trips',{data:{request_id:crypto.randomUUID(),draft:{}}})).json()
 await page.request.post(`/api/city/v1/trips/${trip.id}/exploration/preview`,{data:{request_id:crypto.randomUUID(),expected_version:1,basket_version:0,planning_version:0,constraints:{business_date:'2030-05-01',starts_at:'2030-05-01T02:04:00+08:00',ends_at:'2030-05-01T07:03:00+08:00',origin_text:'开封站',destination_text:'开封站'}}})
 await page.goto(`/assistant?context=city&city_trip=${trip.id}&plan=basket`)
 await page.getByRole('button',{name:'02:04—07:03',exact:true}).click()
 await expect(page.getByLabel('开始时间',{exact:true})).toHaveValue('02:04')
 await page.locator('.planning-question').getByRole('button',{name:'继续',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('开始时间为凌晨')
 await page.getByRole('checkbox',{name:'确认 02:04 为实际的凌晨出发时间（北京时间）',exact:true}).check()
 await page.locator('.planning-question').getByRole('button',{name:'继续',exact:true}).click()
 await expect(page.getByLabel('规划检测结果')).toContainText('位置资料待核验')
})

test('已有核验绑定时使用正式地点ID，仍经原规划器核验且不自动提交',async({page})=>{
 await page.request.post('/api/v1/sessions')
 const trip=await(await page.request.post('/api/city/v1/trips',{data:{request_id:crypto.randomUUID(),draft:{}}})).json()
 await page.request.post(`/api/city/v1/trips/${trip.id}/exploration/preview`,{data:{request_id:crypto.randomUUID(),expected_version:1,basket_version:0,planning_version:0,constraints:{business_date:'2030-05-01',starts_at:'2030-05-01T09:00:00+08:00',ends_at:'2030-05-01T18:00:00+08:00',origin_text:'开封站',destination_place_id:'test:hotel'}}})
 const candidate={candidate_id:'bound',poi_id:'synthetic-poi',name:'[合成测试]已绑定车站',address:'[合成测试]车站出口',longitude:114.3,latitude:34.8,category:'车站',entrance_status:'needs_entrance_verification',fact_status:'provider_candidate_only'}
 await page.route('**/api/city/v1/locations/search',r=>r.fulfill({json:{status:'candidates',resolution_id:'bound-resolution',provider_status:'found',candidates:[candidate]}}))
 await page.route('**/api/city/v1/locations/bound-resolution/confirm',r=>r.fulfill({json:{status:'matched_fact',selected:candidate,formal_match:{fact_id:'test:gate',name:'[合成测试]入口',basis:'curated_amap_poi_binding_to_verified_fact'}}}))
 await page.goto(`/assistant?context=city&city_trip=${trip.id}&plan=basket`)
 await page.getByRole('button',{name:'核对出发与返回地点',exact:true}).click()
 await page.getByRole('button',{name:'查找并核对出发地点',exact:true}).click()
 await page.getByRole('button',{name:'确认此地点',exact:true}).click()
 await expect(page.getByRole('combobox',{name:'出发地点',exact:true})).toHaveValue('test:gate')
 await expect(page.getByRole('region',{name:'出发地点地点核对',exact:true})).toContainText('匹配已有核验地点')
 await page.locator('.planning-question').getByRole('button',{name:'继续',exact:true}).click()
 await expect(page.getByLabel('规划检测结果')).toContainText('信息不足')
 const workspace=await(await page.request.get(`/api/city/v1/trips/${trip.id}/exploration/constraints`)).json()
 expect(workspace.constraints.origin_place_id).toBe('test:gate')
 const saved=await(await page.request.get('/api/city/v1/trips/'+trip.id)).json()
 expect(saved.route_version).toBe(0)
})
