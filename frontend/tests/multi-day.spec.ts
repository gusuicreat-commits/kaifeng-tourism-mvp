import {test,expect,type Page} from '@playwright/test'

async function prepare(page:Page,kind='preview'){
 await page.route('https://**/*',route=>route.abort())
 await page.route('**/api/maps/config',route=>route.fulfill({json:{configured:false}}))
 await page.request.post('/api/v1/sessions')
 const response=await page.request.post('/api/e2e/multi-day',{data:{kind}})
 expect(response.ok(),await response.text()).toBeTruthy()
 const setup=await response.json()
 await page.clock.install({time:new Date(setup.moment)})
 return {...setup,path:'/api/city/v1/trips/'+setup.trip_id}
}

