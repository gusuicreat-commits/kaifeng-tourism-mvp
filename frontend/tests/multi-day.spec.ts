import {test,expect,type Page} from '@playwright/test'

async function prepare(page:Page,kind='preview'){
 await page.route('https://**/*',route=>route.abort())
 await page.route('**/api/maps/config',route=>route.fulfill({json:{configured:false}}))
 await page.request.post('/api/v1/sessions')
 const response=await page.request.post('/api/e2e/multi-day',{data:{kind}})
 expect(response.ok(),await response.text()).toBeTruthy()
 const setup=await response.json()
 await page.clock.install({time:new Date(setup.moment)})
 return {...setup,path:'/api/city/v1/trips/'+setup.trip_id}
}

test('two-day preview folds days, confirms one whole alternative and reads the complete route',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 const setup=await prepare(page)
 await page.goto('/assistant?city_trip='+setup.trip_id+'&plan=basket')
 const preview=page.getByLabel('整套行程方案')
 await expect(preview).toBeVisible();await expect(preview).toContainText('全程步行')
 await expect(preview.locator('.preview-day')).toHaveCount(2)
 const firstState=await(await page.request.get(setup.path)).json()
 expect(firstState.route_version).toBe(0)
 await preview.locator('.preview-day').nth(1).locator('summary').click()
 await expect(preview.locator('.preview-day').nth(1)).toContainText('[合成测试]restaurant')
 await expect(page.getByRole('button',{name:'确认整套方案',exact:true})).toHaveCount(1)
 await page.screenshot({path:'../docs/screenshots/multi-day-preview-mobile.png',fullPage:true})
 const options=preview.getByRole('button',{name:/^方案 /}),count=await options.count()
 expect(count).toBeGreaterThan(0);expect(count).toBeLessThanOrEqual(3)
 const index=count-1;await options.nth(index).click()
 const submitted=page.waitForRequest(r=>r.url().endsWith('/engine/confirm'))
 await page.getByRole('button',{name:'确认整套方案',exact:true}).click()
 expect((await submitted).postDataJSON().alternative_index).toBe(index)
 await expect(page.getByText('已确认并更新正式路线')).toBeVisible()
 await page.getByRole('link',{name:'查看行程',exact:true}).click()
 await expect(page.getByLabel('行程日期')).toBeVisible()
 await expect(page.getByLabel('行程日期').getByRole('button')).toHaveCount(2)
 await expect(page.locator('.journey-page-heading')).toContainText('2 天')
 await page.getByLabel('行程日期').getByRole('button').nth(1).click()
 await expect(page.getByLabel('行程流程安排')).toContainText('[合成测试]restaurant')
 await expect(page.locator('.journey-next-card')).toHaveCount(0)
 await page.screenshot({path:'../docs/screenshots/multi-day-itinerary-mobile.png',fullPage:true})
 const state=await(await page.request.get(setup.path)).json()
 expect(state.route_version).toBe(1);expect(state.draft.days).toHaveLength(2)
 await page.reload();await expect(page.getByLabel('行程日期')).toBeVisible()
 const saved=await(await page.request.get(setup.path+'/engine/current')).json()
 expect(saved.itinerary.days).toHaveLength(2);expect(saved.route_version).toBe(1)
 expect(errors).toEqual([])
})

