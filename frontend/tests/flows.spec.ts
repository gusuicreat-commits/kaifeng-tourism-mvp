 await expect(page.locator('.route-context')).toContainText('暂无客流参考，已按兴趣和步行安排')
 const url=page.url();await page.reload();await expect(page.locator('.itinerary')).toContainText('示意·武侠剧场');expect(page.url()).toBe(url)
 await page.getByRole('link',{name:'调整游玩需求',exact:true}).click()
