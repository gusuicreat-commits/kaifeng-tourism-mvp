import {test,expect} from '@playwright/test'
import {openInterview,fillBasics,finishInterests,setPace,submitPlan} from './interview-helpers'

test('开场只追问缺项，跳过偏好后确认才计算，会话刷新不丢失',async({page})=>{
 let calls=0;page.on('request',r=>{if(r.method()==='POST'&&/\/api\/v1\/trips\/[^/]+\/replan$/.test(r.url()))calls++})
 await openInterview(page)
 await expect(page.getByLabel('游玩日期',{exact:true})).toHaveValue('')
 await expect(page.getByLabel('游玩时长（分钟）',{exact:true})).toHaveValue('')
 await page.getByRole('button',{name:'记下了，继续',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('日期')
 await page.getByLabel('游玩日期',{exact:true}).fill('2026-11-01')
 await page.getByLabel('入园时间',{exact:true}).fill('13:30')
 await expect(page.locator('.interview-question')).toContainText('准备玩多久')
 await expect(page.locator('.interview-question')).not.toContainText('几点入园')
 await page.getByLabel('游玩时长（分钟）',{exact:true}).fill('120')
 await page.getByRole('button',{name:'记下了，继续',exact:true}).click()
 await page.getByRole('button',{name:'暂时没有特别要求',exact:true}).click()
 await page.getByRole('button',{name:'按常规节奏安排',exact:true}).click()
 await expect(page.locator('.memory-status')).not.toContainText('正在保存')
 await page.reload()
 await expect(page.getByRole('button',{name:'确认，生成我的路线',exact:true})).toBeVisible()
 expect(calls).toBe(0)
 await page.setViewportSize({width:390,height:844})
 await page.screenshot({path:'../docs/screenshots/workflow-mobile-review.png',fullPage:true})
 const p=await submitPlan(page)
 expect(p.request.visit_start).toBe('2026-11-01T13:30:00+08:00')
 expect(p.request.mode).toBe('preference');expect(p.request.walking).toBe('normal')
 expect(calls).toBe(1)
})

test('切换景区清除必去点，保留时间并重新询问地点',async({page})=>{
 await openInterview(page);await fillBasics(page)
 await page.getByRole('checkbox',{name:'示意·武侠剧场',exact:true}).check()
 await finishInterests(page);await setPace(page)
 await page.getByRole('button',{name:'修改基本安排',exact:true}).click()
 await page.getByRole('button',{name:'清明上河园',exact:true}).click()
 await expect(page.getByLabel('入园时间',{exact:true})).toHaveValue('13:00')
 await page.getByRole('button',{name:'记下了，继续',exact:true}).click()
 await expect(page.getByRole('checkbox',{name:'景龙湖演出区',exact:true})).not.toBeChecked()
 await expect(page.getByRole('complementary',{name:'我的游览需求'})).not.toContainText('示意·武侠剧场')
 await page.getByRole('button',{name:'继续，安排节奏',exact:true}).click()
 // Previous pace remains answered; no duplicate questions.
 await expect(page.getByRole('button',{name:'确认，生成我的路线',exact:true})).toBeVisible()
 const p=await submitPlan(page);expect(p.request.scenic_id).toBe('qingming');expect(p.request.must_visit).toEqual([])
})

