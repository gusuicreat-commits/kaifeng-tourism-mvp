test('路网失败阻止虚构路线，可重试恢复；无日程不承诺看演出',async({page})=>{
 await page.route('**/api/scenics/wansui/network',r=>r.abort())
 await page.route('**/api/scenics/wansui/schedules?*',r=>r.abort())
 await openInterview(page);await fillBasics(page)
 await expect(page.getByText('演出日程暂不可用，请稍后重试；未核实场次不作观看承诺。')).toBeVisible()
 await finishInterests(page);await setPace(page)
 await expect(page.getByRole('button',{name:'确认，生成我的路线',exact:true})).toBeDisabled()
 await page.unroute('**/api/scenics/wansui/network')
 await page.getByRole('button',{name:'重试地点加载',exact:true}).click()
 await expect(page.getByRole('button',{name:'确认，生成我的路线',exact:true})).toBeEnabled()
 await submitPlan(page);await expect(page.locator('.itinerary')).toBeVisible()
})

