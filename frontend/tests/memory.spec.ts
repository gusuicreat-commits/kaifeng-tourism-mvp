import {test,expect} from '@playwright/test'
import {openInterview,fillBasics,finishInterests,setPace,submitPlan} from './interview-helpers'

test('M7：确认后更新同一行程版本，删除指定站点并跨刷新恢复',async({page})=>{
 await openInterview(page);await fillBasics(page,240)
 await page.getByRole('group',{name:'兴趣偏好'}).getByRole('button',{name:'文化体验',exact:true}).click()
 await page.getByRole('checkbox',{name:'示意·武侠剧场',exact:true}).check()
 await finishInterests(page);await setPace(page)
 const first=await submitPlan(page);await expect(page).toHaveURL(/\/result\//)
 await page.getByRole('link',{name:'调整游玩需求',exact:true}).click()
 await page.getByLabel('也可以直接告诉小汴梁',{exact:true}).fill('今天少走路')
 await page.getByRole('button',{name:'发送安排',exact:true}).click()
 await expect(page.getByRole('button',{name:'确认调整并重新规划',exact:true})).toBeVisible()
 const before=await (await page.request.get('/api/v1/trips/'+first.trip_id)).json()
 expect(before.route_version).toBe(1)
 const commit=page.waitForResponse(r=>r.url().endsWith('/confirm')&&r.request().method()==='POST')
 await page.getByRole('button',{name:'确认调整并重新规划',exact:true}).click()
 const second=await (await commit).json()
 expect(second.trip.id).toBe(first.trip_id);expect(second.trip.route_version).toBe(2)
 expect(second.trip.constraints.must_visit).toEqual(['theatre']);expect(second.trip.constraints.available_minutes).toBe(240)
 await expect(page).toHaveURL('/result/'+second.plan.id)
 await page.reload();await expect(page.locator('.itinerary')).toContainText('示意·武侠剧场')
 await page.getByRole('link',{name:'调整游玩需求',exact:true}).click()
 const stops=second.plan.stops.slice(1,-1)
 const index=stops.findIndex((s:{id:string})=>s.id!=='theatre')+1
 expect(index).toBeGreaterThan(0)
 await page.getByLabel('也可以直接告诉小汴梁',{exact:true}).fill(`第${index}个点不去了`)
 await page.getByRole('button',{name:'发送安排',exact:true}).click()
 await expect(page.locator('.memory-proposal')).toContainText(stops[index-1].name.replace('（示意位置）','').replace('演示·',''))
 const next=page.waitForResponse(r=>r.url().endsWith('/confirm')&&r.request().method()==='POST')
 await page.getByRole('button',{name:'确认调整并重新规划',exact:true}).click()
 const third=await (await next).json()
 expect(third.trip.route_version).toBe(3)
 expect(third.plan.stops.map((s:{id:string})=>s.id)).not.toContain(stops[index-1].id)
 expect(third.plan.stops.map((s:{id:string})=>s.id)).toContain('theatre')
})

