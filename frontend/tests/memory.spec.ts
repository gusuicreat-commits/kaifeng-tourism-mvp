test('M7：旧页面不能静默覆盖另一标签页已提交的新路线',async({page,context})=>{
 await openInterview(page);await fillBasics(page);await finishInterests(page);await setPace(page)
 const p=await submitPlan(page);await expect(page).toHaveURL(/\/result\//)
 const other=await context.newPage();await other.goto(page.url())
 await other.getByRole('button',{name:'尽量避拥挤',exact:true}).click()
 await expect(other).not.toHaveURL(page.url())
 await page.getByRole('button',{name:'少走路',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('另一请求修改')
 const current=await (await page.request.get('/api/v1/trips/'+p.trip_id)).json()
 expect(current.route_version).toBe(2)
 expect(current.route_id).toBe(other.url().split('/').pop())
})

